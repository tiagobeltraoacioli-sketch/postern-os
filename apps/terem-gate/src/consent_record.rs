    #[test]
    fn four_revocation_paths_each_deny() {
        let mut a = authority();
        let pub_ = a.host_pub();

        // Path #1: explicit revoke by id.
        {
            let mut l = ConsentLedger::new(pub_);
            let rec = a
                .mint(IID, Capability::Clipboard, h2g(), ConsentScope::Session, NOW, NOW + 600, "g")
                .unwrap();
            let id = rec.id;
            l.admit(rec).unwrap();
            l.revoke(id);
            assert_eq!(
                l.authorize(&IID, Capability::Clipboard, World::Host, World::Guest, NOW, None),
                Err(TeremGateError::Revoked)
            );
        }
        // Path #2: bridge lane closed.
        {
            let mut l = ConsentLedger::new(pub_);
            let rec = a
                .mint(IID, Capability::Network, h2g(), ConsentScope::Session, NOW, NOW + 600, "g")
                .unwrap();
            l.admit(rec).unwrap();
            l.revoke_capability(Capability::Network);
            assert_eq!(
                l.authorize(&IID, Capability::Network, World::Host, World::Guest, NOW, None),
                Err(TeremGateError::CapabilityClosed)
            );
        }
        // Path #3: kill-switch.
        {
            let mut l = ConsentLedger::new(pub_);
            let rec = a
                .mint(IID, Capability::Audio, h2g(), ConsentScope::Session, NOW, NOW + 600, "g")
                .unwrap();
            l.admit(rec).unwrap();
            l.engage_kill_switch();
            assert_eq!(
                l.authorize(&IID, Capability::Audio, World::Host, World::Guest, NOW, None),
                Err(TeremGateError::KillSwitchEngaged)
            );
            l.disengage_kill_switch();
            assert!(l
                .authorize(&IID, Capability::Audio, World::Host, World::Guest, NOW, None)
                .is_ok());
        }
        // Path #4: expiry.
        {
            let mut l = ConsentLedger::new(pub_);
            let rec = a
                .mint(IID, Capability::Clipboard, g2h(), ConsentScope::Session, NOW, NOW + 5, "g")
                .unwrap();
            l.admit(rec).unwrap();
            assert_eq!(
                l.authorize(&IID, Capability::Clipboard, World::Guest, World::Host, NOW + 5, None),
                Err(TeremGateError::Expired)
            );
        }
    }

