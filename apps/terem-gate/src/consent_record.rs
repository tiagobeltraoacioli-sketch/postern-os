    #[test]
    fn a_guest_holding_a_foreign_key_cannot_self_authorize() {
        // Simulates a compromised guest that generates its OWN keypair and
        // tries to mint its own "yes". The ledger only trusts the host's
        // pinned key, so the forged record is refused before it ever enters
        // the ledger -- it cannot even be admitted, let alone authorize a
        // crossing.
        let mut host = authority();
        let mut guest_forged_authority = ConsentAuthority::from_seed([0xEE; 32]);
        let forged_clipboard = guest_forged_authority
            .mint(IID, Capability::Clipboard, h2g(), ConsentScope::Session, NOW, NOW + 600, "self-granted")
            .unwrap();
        let mut ledger = ConsentLedger::new(host.host_pub());
        assert_eq!(ledger.admit(forged_clipboard), Err(TeremGateError::BadSignature));

        // The genuine host record admits and authorizes fine.
        let genuine = host
            .mint(IID, Capability::Clipboard, h2g(), ConsentScope::Session, NOW, NOW + 600, "host-granted")
            .unwrap();
        assert!(ledger.admit(genuine).is_ok());
        assert!(ledger
            .authorize(&IID, Capability::Clipboard, World::Host, World::Guest, NOW, None)
            .is_ok());
    }

